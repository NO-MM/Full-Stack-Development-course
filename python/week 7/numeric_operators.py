#Operators

#Addition (+)
#Subtraction (-)
#Multiplication (*)
#Division (/)
#Modulus (%)
#Exponentiation (**)

x = 10
y = 2

print(x+y)
print(x-y)
print(x*y)
print(x/y)
print(x%y)
print(5%2)  # Modulus operation
