#Dictionary example

my_dict = {'apple': 3, 'banana': 5, 'cherry': 2}  # Creating a dictionary with key-value pairs

print(my_dict['apple'])  # Accessing the value associated with the key 'apple'

my_dict['grapes'] = 4  # Adding a new key-value pair to the dictionary
print(my_dict)  # Printing the updated dictionary

my_dict['banana'] = 7  # Modifying the value associated with the key 'banana'
print(my_dict)  # Printing the dictionary after modification