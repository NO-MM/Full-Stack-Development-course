#Tuples

my_tuple = (1, 2, 3, 4, 5)  # Creating a tuple with float values

print(my_tuple)  # Printing the tuple
print(my_tuple[0])  # Accessing the first element of the tuple
print(my_tuple[2])  # Accessing the first element of the tuple
print(my_tuple[-1])  # Accessing the last element of the tuple

tuple1 = (1, 2, 3)  # Creating a tuple with integers
tuple2 = (4, 5, 6)  # Creating another tuple with integers

# Concatenating two tuples
conc_tuple = tuple1 + tuple2
